#!/usr/bin/env bash
#
# Checks a pull request's title and description as the commit message they become: pull requests are squashed, the
# title is the subject line and the description the body. Reads PR_TITLE and PR_BODY from the environment, so text
# written by anyone never passes through a shell command line. The rule is in AGENTS.md, "Pull requests".

set -euf -o pipefail
export LC_ALL="C.UTF-8"
PS4='+ $(date -u +%Y-%m-%dT%H:%M:%S%z) ${BASH_SOURCE[0]##*/}:${LINENO}: '

# GitHub adds " (#123)" to the subject; 65 keeps the whole line within 72.
readonly MAX_TITLE=65

status=0

function fail() {
  echo "$1" >&2
  status=1
}

# Fails when a line of the body matches the pattern, and shows the lines.
function forbid() {
  local pattern="$1" why="$2" found
  if found="$(grep -nE -- "${pattern}" <<<"${PR_BODY}")"; then
    fail "${why}:"
    echo "${found}" >&2
  fi
}

function main() {
  : "${PR_TITLE:?PR_TITLE must be set}"
  PR_BODY="${PR_BODY:-}"
  # Descriptions written in the browser come with CRLF line ends.
  PR_BODY="${PR_BODY//$'\r'/}"

  if ((${#PR_TITLE} > MAX_TITLE)); then
    fail "title has ${#PR_TITLE} characters, at most ${MAX_TITLE} are allowed"
  fi
  if [[ "${PR_TITLE}" == *. ]]; then
    fail "title ends with a full stop"
  fi

  # Markdown is welcome. What is refused is what says nothing about the change once it is a commit.
  forbid '^[[:space:]]*[-*] \[[ xX]\]' 'a checklist belongs in a comment, not in the commit message'
  forbid '<!--|^[[:space:]]*</?[a-zA-Z]' 'HTML does not belong in a commit message'
  forbid '^(Co-authored-by|Signed-off-by|Generated with|Generated by)' 'no trailers'

  if ((status != 0)); then
    echo "The title and description become the commit on main: see AGENTS.md, \"Pull requests\"." >&2
  fi
  return "${status}"
}

main "$@"

